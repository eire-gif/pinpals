-- 0187 — Multi-day championships (Oct 2026)
--
-- Asked by Eire, 23 Oct 2026: a leaderboard over 2, 3 or 4 days, a different
-- course (and format) each day, PGA style, with each player's place up or
-- down against the day before. For societies, trips and Golf Buddies; on a
-- trip, "Run a leaderboard across the trip" turns the itinerary's rounds into
-- the championship's days. Mock-ups approved: canvas "PinPals — multi-round
-- leaderboard".
--
-- The days are ordinary events: a championship's days are day outs
-- (society_outings, kind 'day') with championship_id and championship_round
-- set, so each keeps its own entries, draw, live set-up, start, card and
-- published results exactly as any day out. A trip's championship takes its
-- days from the trip's round items instead (trip_outing_id), which now
-- remember the live day they became (society_outing_items.match_day_id) —
-- the gap noted in claude/outing-itineraries.md "Next 1".
--
-- How the days add up (same points, same strokes → added; mixed → places
-- points each day) is worked out in src/lib/championship.ts from the days'
-- formats; `rule` is the organiser's choice: 'auto' or 'places'.
--
-- Writes only through functions:
--   save_championship(group, id, p)   create or change it and its day outs
--   cancel_championship(id)           cancels the days not yet played
--   set_championship_entry(id, in, member)  join or leave every open day
--   set_trip_championship(trip, on, rule)   the trip toggle
--   link_outing_item_match_day(item, day)   a trip round's live day
--
-- No drop statements. Applied to production 23 Oct 2026.
--
-- Rollback:
--   drop function if exists public.save_championship(bigint, bigint, jsonb);
--   drop function if exists public.cancel_championship(bigint);
--   drop function if exists public.set_championship_entry(bigint, boolean, uuid);
--   drop function if exists public.set_trip_championship(bigint, boolean, text);
--   drop function if exists public.link_outing_item_match_day(bigint, bigint);
--   alter table public.society_outing_items drop column if exists match_day_id;
--   alter table public.society_outings drop column if exists championship_id,
--     drop column if exists championship_round, drop column if exists championship_format;
--   drop table if exists public.group_championships;

create table if not exists public.group_championships (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.groups(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 80),
  rule text not null default 'auto' check (rule in ('auto', 'places')),
  trip_outing_id bigint unique references public.society_outings(id) on delete cascade,
  status text not null default 'open' check (status in ('open', 'cancelled')),
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.group_championships is
  'Multi-day championships (0187): one leaderboard over 2–4 days. Days are day outs with championship_id set, or a trip''s round items (trip_outing_id).';

create index if not exists group_championships_group_idx on public.group_championships (group_id);

alter table public.group_championships enable row level security;

create policy "group members read championships" on public.group_championships
  for select to authenticated
  using (public.is_group_member(group_id, (select auth.uid())));

revoke all on public.group_championships from anon;
revoke insert, update, delete on public.group_championships from authenticated;
grant select on public.group_championships to authenticated;

alter table public.society_outings
  add column if not exists championship_id bigint references public.group_championships(id) on delete set null,
  add column if not exists championship_round smallint check (championship_round between 1 and 4),
  add column if not exists championship_format text check (championship_format in (
    'stableford', 'stroke', 'scramble2', 'scramble4', 'foursomesPts', 'foursomesNet', 'greensomesPts', 'greensomesNet'));

comment on column public.society_outings.championship_format is
  'Multi-day championships (0187): the day''s planned format, as the app''s Start a Round names them. The live day''s own format counts once it starts.';

create unique index if not exists society_outings_championship_round_idx
  on public.society_outings (championship_id, championship_round)
  where championship_id is not null and status = 'open';

alter table public.society_outing_items
  add column if not exists match_day_id bigint references public.live_match_days(id) on delete set null;

comment on column public.society_outing_items.match_day_id is
  'A trip round''s live day (0187), set when the round is started.';


-- ============ Create or change a championship ============
--
-- p: { title, rule, details, entry_fee_cents, max_entries,
--      days: [{ plays_on, club_id, course_name, first_tee, format }] }  2–4 days
-- Days must be in date order, the first from today, the last at most 20 days
-- after the first. Each day is saved through save_outing (so a day out's own
-- rules all apply); a day that has started (or passed) is left as it is.
-- Fewer days than before: the dropped days are cancelled, if not started.

create or replace function public.save_championship(p_group_id bigint, p_id bigint, p jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := (select auth.uid());
  cur public.group_championships%rowtype;
  v_title text := btrim(coalesce(p ->> 'title', ''));
  v_rule text := coalesce(nullif(p ->> 'rule', ''), 'auto');
  v_days jsonb := p -> 'days';
  v_n integer;
  v_id bigint;
  v_day jsonb;
  v_i integer;
  v_date date;
  v_prev date;
  v_first date;
  v_format text;
  v_existing public.society_outings%rowtype;
  v_outing bigint;
  v_today date := (now() at time zone 'Europe/Dublin')::date;
begin
  if not public.outing_officer(p_group_id, me) then
    raise exception 'Only whoever runs the group can set up events.' using errcode = '42501';
  end if;
  if coalesce((select kind from public.groups where id = p_group_id and hidden_at is null), '') not in ('society', 'crew', 'trip') then
    raise exception 'Championships are for societies, Golf Buddies and trips.';
  end if;
  if p_id is not null then
    select * into cur from public.group_championships where id = p_id and group_id = p_group_id;
    if not found or cur.trip_outing_id is not null then raise exception 'That championship can''t be changed here.'; end if;
    if cur.status <> 'open' then raise exception 'That championship was cancelled.'; end if;
  end if;
  if char_length(v_title) = 0 then raise exception 'Give the championship a name.'; end if;
  if char_length(v_title) > 80 then raise exception 'That name is too long — 80 characters at most.'; end if;
  if v_rule not in ('auto', 'places') then raise exception 'Choose how the days add up.'; end if;
  if jsonb_typeof(v_days) <> 'array' then raise exception 'Add the days.'; end if;
  v_n := jsonb_array_length(v_days);
  if v_n < 2 or v_n > 4 then raise exception 'A championship is 2, 3 or 4 days.'; end if;

  -- Dates in order, within three weeks. A day already played or started
  -- keeps its stored date, so that's the one checked.
  for v_i in 0 .. v_n - 1 loop
    v_date := null;
    if p_id is not null then
      select o.plays_on into v_date from public.society_outings o
       where o.championship_id = p_id and o.championship_round = v_i + 1 and o.status = 'open'
         and (o.match_day_id is not null or o.plays_on < v_today);
    end if;
    if v_date is null then
      begin
        v_date := (v_days -> v_i ->> 'plays_on')::date;
      exception when others then
        raise exception 'That date doesn''t look right.';
      end;
    end if;
    if v_date is null then raise exception 'Choose a date for day %.', v_i + 1; end if;
    if v_i = 0 then v_first := v_date; end if;
    if v_prev is not null and v_date <= v_prev then raise exception 'Each day comes after the one before.'; end if;
    v_prev := v_date;
    v_format := coalesce(nullif(v_days -> v_i ->> 'format', ''), 'stableford');
    if v_format not in ('stableford', 'stroke', 'scramble2', 'scramble4', 'foursomesPts', 'foursomesNet', 'greensomesPts', 'greensomesNet') then
      raise exception 'Choose a format for day %.', v_i + 1;
    end if;
  end loop;
  if v_prev > v_first + 20 then raise exception 'A championship is three weeks at most.'; end if;

  if p_id is null then
    if (select count(*) from public.group_championships where group_id = p_group_id and status = 'open' and created_at > now() - interval '1 day') >= 10 then
      raise exception 'That''s a lot of championships in a day.';
    end if;
    insert into public.group_championships (group_id, title, rule, created_by)
    values (p_group_id, v_title, v_rule, me)
    returning id into v_id;
  else
    v_id := p_id;
    update public.group_championships set title = v_title, rule = v_rule, updated_at = now() where id = v_id;
  end if;

  for v_i in 0 .. v_n - 1 loop
    v_day := v_days -> v_i;
    select * into v_existing from public.society_outings
     where championship_id = v_id and championship_round = v_i + 1 and status = 'open';
    if found and (v_existing.match_day_id is not null or v_existing.plays_on < v_today) then
      continue; -- played or started: left as it is
    end if;
    v_outing := public.save_outing(p_group_id, case when found then v_existing.id else null end, jsonb_build_object(
      'kind', 'day',
      'title', v_title || ' · Day ' || (v_i + 1),
      'plays_on', v_day ->> 'plays_on',
      'club_id', v_day ->> 'club_id',
      'course_name', v_day ->> 'course_name',
      'first_tee', v_day ->> 'first_tee',
      'details', p ->> 'details',
      'entry_fee_cents', case when v_i = 0 then p ->> 'entry_fee_cents' else null end,
      'max_entries', p ->> 'max_entries',
      'format_label', v_day ->> 'format_label'
    ));
    update public.society_outings
       set championship_id = v_id,
           championship_round = v_i + 1,
           championship_format = coalesce(nullif(v_day ->> 'format', ''), 'stableford')
     where id = v_outing;
  end loop;

  -- Days beyond the new count: cancel the ones not started.
  for v_existing in
    select * from public.society_outings where championship_id = v_id and championship_round > v_n and status = 'open'
  loop
    if v_existing.match_day_id is not null then
      raise exception 'Day % has started, so the championship can''t be shorter than that.', v_existing.championship_round;
    end if;
    perform public.cancel_outing(v_existing.id);
    update public.society_outings set championship_id = null, championship_round = null where id = v_existing.id;
  end loop;

  return v_id;
end;
$$;
revoke all on function public.save_championship(bigint, bigint, jsonb) from public, anon, authenticated;
grant execute on function public.save_championship(bigint, bigint, jsonb) to authenticated;


-- ============ Cancel ============

create or replace function public.cancel_championship(p_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := (select auth.uid());
  c public.group_championships%rowtype;
  o public.society_outings%rowtype;
begin
  select * into c from public.group_championships where id = p_id;
  if not found or not public.outing_officer(c.group_id, me) then
    raise exception 'Only whoever runs the group can cancel it.' using errcode = '42501';
  end if;
  for o in select * from public.society_outings where championship_id = p_id and status = 'open' and match_day_id is null loop
    perform public.cancel_outing(o.id);
  end loop;
  update public.group_championships set status = 'cancelled', updated_at = now() where id = p_id;
end;
$$;
revoke all on function public.cancel_championship(bigint) from public, anon, authenticated;
grant execute on function public.cancel_championship(bigint) to authenticated;


-- ============ Join or leave every open day ============
--
-- Goes day by day through set_outing_entry, so each day's own rules (closing
-- at midnight, places, requests, the officers' say) apply. A day that can't
-- be changed any more (closed, started, full) is skipped; if none could be,
-- the first day's reason is given.

create or replace function public.set_championship_entry(p_id bigint, p_in boolean, p_member uuid default null)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := (select auth.uid());
  c public.group_championships%rowtype;
  o public.society_outings%rowtype;
  v_done integer := 0;
  v_reason text;
begin
  select * into c from public.group_championships where id = p_id;
  if not found or not public.is_group_member(c.group_id, me) then
    raise exception 'That championship isn''t available.';
  end if;
  if c.status <> 'open' then raise exception 'That championship was cancelled.'; end if;
  if c.trip_outing_id is not null then
    raise exception 'Join the trip itself — its leaderboard follows the trip.';
  end if;
  for o in
    select * from public.society_outings where championship_id = p_id and status = 'open' order by championship_round
  loop
    begin
      perform public.set_outing_entry(o.id, p_in, p_member);
      v_done := v_done + 1;
    exception when others then
      if sqlstate = '42501' then raise; end if;
      v_reason := coalesce(v_reason, sqlerrm);
    end;
  end loop;
  if v_done = 0 and v_reason is not null then raise exception '%', v_reason; end if;
  return v_done;
end;
$$;
revoke all on function public.set_championship_entry(bigint, boolean, uuid) from public, anon, authenticated;
grant execute on function public.set_championship_entry(bigint, boolean, uuid) to authenticated;


-- ============ A trip's leaderboard ============

create or replace function public.set_trip_championship(p_outing_id bigint, p_on boolean, p_rule text default 'auto')
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := (select auth.uid());
  o public.society_outings%rowtype;
  v_id bigint;
begin
  select * into o from public.society_outings where id = p_outing_id;
  if not found or not public.outing_officer(o.group_id, me) then
    raise exception 'Only whoever runs the trip can change this.' using errcode = '42501';
  end if;
  if coalesce(o.kind, 'day') = 'day' then raise exception 'A leaderboard across the trip is for overnight and abroad trips.'; end if;
  if o.status <> 'open' then raise exception 'This trip was cancelled.'; end if;
  if coalesce(p_rule, 'auto') not in ('auto', 'places') then raise exception 'Choose how the days add up.'; end if;

  select id into v_id from public.group_championships where trip_outing_id = p_outing_id;
  if p_on then
    if v_id is null then
      insert into public.group_championships (group_id, title, rule, trip_outing_id, created_by)
      values (o.group_id, o.title, coalesce(p_rule, 'auto'), p_outing_id, me)
      returning id into v_id;
    else
      update public.group_championships
         set status = 'open', rule = coalesce(p_rule, rule), title = o.title, updated_at = now()
       where id = v_id;
    end if;
  elsif v_id is not null then
    update public.group_championships set status = 'cancelled', updated_at = now() where id = v_id;
  end if;
  return v_id;
end;
$$;
revoke all on function public.set_trip_championship(bigint, boolean, text) from public, anon, authenticated;
grant execute on function public.set_trip_championship(bigint, boolean, text) to authenticated;


-- ============ A trip round's live day ============

create or replace function public.link_outing_item_match_day(p_item_id bigint, p_match_day_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  me uuid := (select auth.uid());
  v_group bigint;
  v_kind text;
begin
  select o.group_id, i.kind into v_group, v_kind
    from public.society_outing_items i join public.society_outings o on o.id = i.outing_id
   where i.id = p_item_id;
  if v_group is null or not public.outing_officer(v_group, me) then
    raise exception 'Only whoever runs the trip can start its rounds.' using errcode = '42501';
  end if;
  if v_kind <> 'round' then raise exception 'That isn''t a round.'; end if;
  if not exists (select 1 from public.live_match_days where id = p_match_day_id and created_by = me) then
    raise exception 'That isn''t your round.';
  end if;
  update public.society_outing_items set match_day_id = p_match_day_id where id = p_item_id;
end;
$$;
revoke all on function public.link_outing_item_match_day(bigint, bigint) from public, anon, authenticated;
grant execute on function public.link_outing_item_match_day(bigint, bigint) to authenticated;
