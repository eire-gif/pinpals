-- Let `clubs.id` accept an explicit value, so the course importer can upsert.
--
-- 0001 declared it `generated always as identity`, which forbids supplying a
-- value at all — `cannot insert a non-DEFAULT value into column "id"`. An
-- upsert is an `INSERT ... ON CONFLICT (id) DO UPDATE` underneath, so the
-- statement carries an id in its insert tuple even when every row is
-- destined for the UPDATE branch. `generated always` therefore rejects the
-- whole batch. The importer hit this on its first run against Ireland, where
-- the 373 seeded rows are all updates rather than inserts.
--
-- `by default` still generates an id for every insert that omits one, so
-- nothing about how rows are normally created changes. What it also allows
-- is an insert that names an id explicitly, which would not advance the
-- sequence and could collide later — worth knowing, but no code does that:
-- the only explicit ids come from an upsert of rows that already exist, so
-- they always resolve to the UPDATE branch and never reach the sequence.
--
-- The alternative was a service-role-only bulk-update RPC taking a JSONB
-- array. That is more machinery to maintain for the same result, and it
-- would leave the ordinary supabase-js upsert broken for whatever needs it
-- next.

alter table public.clubs alter column id set generated by default;
