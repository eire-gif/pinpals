-- ============ 8. The knockout ============

-- p_bracket: qualifiers in bracket order, 2, 4, 8, 16 or 32 long; null is a
-- bye. Positions 1 and 2 meet, 3 and 4, and so on; the winners of 1v2 and
-- 3v4 meet next. Worked out on the organiser's phone from the group tables
-- (lib/matchplay.ts) and checked here: everyone has entered, no one twice,
-- and no match is a bye against a bye.
create or replace function public.competition_start_knockout(p_league_id bigint, p_bracket jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  l public.competition_leagues;
  v_players uuid[];
  v_size integer;
  v_rounds integer;
  v_level integer;
  v_count integer;
  v_j integer;
  v_stage text;
  v_ids bigint[];
  v_prev bigint[];
  v_id bigint;
  v_a uuid;
  v_b uuid;
  v_seen uuid[] := '{}';
  v_x uuid;
  r record;
begin
  if not public.competition_is_organiser(p_league_id) then
    raise exception 'Only the organiser can start the knockout.' using errcode = '42501';
  end if;
  select * into l from public.competition_leagues where id = p_league_id for update;
  if l.kind <> 'league' or l.status <> 'running' then raise exception 'The knockout follows the groups.'; end if;
  if exists (select 1 from public.competition_matches where league_id = p_league_id and stage = 'group' and status in ('open', 'reported', 'disputed')) then
    raise exception 'Every group match must be settled first: confirmed, given as a walkover, or voided.';
  end if;
  if jsonb_typeof(p_bracket) <> 'array' then raise exception 'The bracket is a list of players.'; end if;
  select array_agg(case when jsonb_typeof(value) = 'null' then null else (value #>> '{}')::uuid end order by ord)
    into v_players from jsonb_array_elements(p_bracket) with ordinality t(value, ord);
  v_size := coalesce(cardinality(v_players), 0);
  if v_size not in (2, 4, 8, 16, 32) then raise exception 'A knockout has 2, 4, 8, 16 or 32 places.'; end if;
  foreach v_x in array v_players loop
    if v_x is null then continue; end if;
    if not exists (select 1 from public.competition_entries where league_id = p_league_id and user_id = v_x and withdrawn_at is null) then
      raise exception 'Everyone in the knockout must have entered.';
    end if;
    if v_x = any(v_seen) then raise exception 'Each player goes in once.'; end if;
    v_seen := v_seen || v_x;
  end loop;

  v_rounds := round(log(2::numeric, v_size::numeric))::integer;
  -- Build from the final outwards, so each match knows where its winner goes.
  for v_level in 0 .. v_rounds - 1 loop
    v_count := power(2, v_level)::integer;
    v_stage := case v_count when 1 then 'final' when 2 then 'sf' when 4 then 'qf' when 8 then 'r16' else 'r32' end;
    v_ids := '{}';
    for v_j in 0 .. v_count - 1 loop
      v_a := null; v_b := null;
      if v_level = v_rounds - 1 then
        v_a := v_players[2 * v_j + 1];
        v_b := v_players[2 * v_j + 2];
        if v_a is null and v_b is null then raise exception 'A bye can''t meet a bye.'; end if;
      end if;
      insert into public.competition_matches (league_id, stage, round_no, slot, player_a, player_b, play_by, next_match_id, next_slot)
      values (p_league_id, v_stage, v_rounds - v_level, v_j + 1, v_a, v_b,
        current_date + ((v_rounds - v_level) * l.round_days) - 1,
        case when v_level = 0 then null else v_prev[v_j / 2 + 1] end,
        case when v_level = 0 then null when v_j % 2 = 0 then 'a' else 'b' end)
      returning id into v_id;
      v_ids := v_ids || v_id;
    end loop;
    v_prev := v_ids;
  end loop;

  update public.competition_leagues set status = 'knockout', updated_at = now() where id = p_league_id;

  -- Byes go straight through.
  for r in select id, player_a, player_b from public.competition_matches
           where league_id = p_league_id and stage <> 'group' and round_no = 1 and (player_a is null or player_b is null) loop
    update public.competition_matches set status = 'confirmed', confirmed_at = now(),
      winner = case when r.player_a is null then 'b' else 'a' end, margin = 'bye', holes_up = 0
    where id = r.id;
    perform public.competition_after_result(r.id);
  end loop;

  for r in select unnest(v_seen) as user_id loop
    perform public.competition_alert(r.user_id, 'competition', 'You''re in the knockout: ' || l.name,
      'The draw is made. See who you play.', jsonb_build_object('href', '/compete/' || p_league_id),
      'competition-knockout-' || p_league_id);
  end loop;
end;
$$;
revoke all on function public.competition_start_knockout(bigint, jsonb) from public, anon, authenticated;
grant execute on function public.competition_start_knockout(bigint, jsonb) to authenticated;

-- ============ 9. Ladders ============

create or replace function public.competition_challenge(p_league_id bigint, p_opponent uuid)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  l public.competition_leagues;
  v_me integer;
  v_them integer;
  v_id bigint;
  v_name text;
begin
  select * into l from public.competition_leagues where id = p_league_id for update;
  if l.id is null or l.kind <> 'ladder' or not public.competition_can_view(p_league_id) then
    raise exception 'That ladder is not open to you.' using errcode = '42501';
  end if;
  if l.status <> 'running' then raise exception 'This ladder has finished.'; end if;
  select ladder_position into v_me from public.competition_entries where league_id = p_league_id and user_id = v_uid and withdrawn_at is null;
  select ladder_position into v_them from public.competition_entries where league_id = p_league_id and user_id = p_opponent and withdrawn_at is null;
  if v_me is null then raise exception 'Join the ladder first.'; end if;
  if v_them is null then raise exception 'They are not on this ladder.'; end if;
  if not (v_them < v_me and v_them >= v_me - l.challenge_reach) then
    raise exception 'You can challenge someone up to % places above you.', l.challenge_reach;
  end if;
  if exists (select 1 from public.competition_matches where league_id = p_league_id and status in ('open', 'reported', 'disputed')
             and (v_uid in (player_a, player_b) or p_opponent in (player_a, player_b))) then
    raise exception 'One of you already has a challenge to play.';
  end if;
  insert into public.competition_matches (league_id, stage, player_a, player_b, play_by)
  values (p_league_id, 'ladder', v_uid, p_opponent, current_date + l.challenge_days)
  returning id into v_id;
  v_name := coalesce((select nullif(btrim(first_name), '') from public.profiles where id = v_uid), 'A member');
  perform public.competition_alert(p_opponent, 'competition', v_name || ' has challenged you',
    'On the ' || l.name || '. Play by ' || to_char(current_date + l.challenge_days, 'DD Mon') || '.',
    jsonb_build_object('href', '/compete/match/' || v_id), null);
  return v_id;
end;
$$;
revoke all on function public.competition_challenge(bigint, uuid) from public, anon, authenticated;
grant execute on function public.competition_challenge(bigint, uuid) to authenticated;

