create or replace function public.open_competition_share(p jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  v_club bigint := nullif(p ->> 'club_id', '')::bigint;
  v_date date := nullif(p ->> 'plays_on', '')::date;
  v_title text := btrim(coalesce(p ->> 'title', ''));
  v_url text := nullif(btrim(coalesce(p ->> 'booking_url', '')), '');
  v_province text := nullif(p ->> 'province', '');
  v_id bigint;
begin
  if v_uid is null then raise exception 'Sign in first.' using errcode = '42501'; end if;
  if v_club is null or not exists (select 1 from public.clubs where id = v_club and hidden_at is null) then
    raise exception 'Choose the club running it.';
  end if;
  if v_date is null or v_date < current_date or v_date > current_date + 365 then
    raise exception 'Pick a date in the next year.';
  end if;
  if char_length(v_title) not between 3 and 80 then raise exception 'Say what the competition is, e.g. Fourball open.'; end if;
  if v_url is not null and (v_url !~ '^https://' or char_length(v_url) > 500) then
    raise exception 'The booking link must start with https://';
  end if;
  if v_province is not null and v_province not in ('leinster', 'munster', 'connacht', 'ulster') then
    raise exception 'Choose a province.';
  end if;
  if (select count(*) from public.open_competitions where posted_by = v_uid and created_at > now() - interval '1 day') >= 10 then
    raise exception 'That''s plenty for one day. Try again tomorrow.';
  end if;
  if exists (select 1 from public.open_competitions where club_id = v_club and plays_on = v_date and hidden_at is null
             and lower(title) = lower(v_title)) then
    raise exception 'That open is already listed.';
  end if;
  insert into public.open_competitions (club_id, plays_on, title, entry_fee, booking_url, province, posted_by)
  values (v_club, v_date, v_title, nullif(left(btrim(coalesce(p ->> 'entry_fee', '')), 40), ''), v_url, v_province, v_uid)
  returning id into v_id;
  return v_id;
end;
$$;
revoke all on function public.open_competition_share(jsonb) from public, anon, authenticated;
grant execute on function public.open_competition_share(jsonb) to authenticated;

