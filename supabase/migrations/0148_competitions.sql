-- ============ 4. Setting up a league or ladder ============

create or replace function public.competition_league_save(p_id bigint, p jsonb)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  v_group bigint := nullif(p ->> 'group_id', '')::bigint;
  v_kind text := coalesce(nullif(p ->> 'kind', ''), 'league');
  v_name text := btrim(coalesce(p ->> 'name', ''));
  v_about text := nullif(btrim(coalesce(p ->> 'about', '')), '');
  v_province text := nullif(p ->> 'province', '');
  v_club bigint := nullif(p ->> 'club_id', '')::bigint;
  v_fee integer := nullif(p ->> 'entry_fee_cents', '')::integer;
  v_close timestamptz := nullif(p ->> 'entries_close_at', '')::timestamptz;
  v_starts date := nullif(p ->> 'starts_on', '')::date;
  v_max numeric := nullif(p ->> 'max_handicap', '')::numeric;
  v_row public.competition_leagues;
begin
  if v_uid is null then raise exception 'Sign in first.' using errcode = '42501'; end if;
  if v_kind not in ('league', 'ladder') then raise exception 'A competition is a league or a ladder.'; end if;
  if char_length(v_name) not between 3 and 80 then raise exception 'Give it a name of 3 to 80 characters.'; end if;

  if p_id is null then
    if v_group is null then
      if not public.competition_staff() then
        raise exception 'Only PinPals can run a competition open to every member. Start one in your group instead.' using errcode = '42501';
      end if;
    else
      if not exists (select 1 from public.groups where id = v_group and hidden_at is null) then
        raise exception 'That group no longer exists.';
      end if;
      if coalesce(public.group_role(v_group, v_uid), '') not in ('owner', 'admin') then
        raise exception 'Only whoever runs the group can start a competition for it.' using errcode = '42501';
      end if;
    end if;
    if v_kind = 'league' and (v_close is null or v_close <= now()) then
      raise exception 'Set when entries close, in the future.';
    end if;
    if v_kind = 'league' and (v_starts is null or v_starts < (v_close at time zone 'Europe/Dublin')::date) then
      raise exception 'The league starts on or after entries close.';
    end if;

    insert into public.competition_leagues (
      kind, name, about, group_id, province, club_id, created_by, entry_fee_cents, entries_close_at, starts_on, max_handicap,
      qualifiers_per_group, round_days, points_win, points_half, challenge_reach, challenge_days
    ) values (
      v_kind, v_name, v_about, v_group, v_province, v_club, v_uid, v_fee, v_close, v_starts, v_max,
      coalesce(nullif(p ->> 'qualifiers_per_group', '')::smallint, 2),
      coalesce(nullif(p ->> 'round_days', '')::smallint, 14),
      coalesce(nullif(p ->> 'points_win', '')::smallint, 3),
      coalesce(nullif(p ->> 'points_half', '')::smallint, 1),
      coalesce(nullif(p ->> 'challenge_reach', '')::smallint, 3),
      coalesce(nullif(p ->> 'challenge_days', '')::smallint, 14)
    ) returning * into v_row;
    -- A ladder is running from the start: whoever joins goes to the bottom.
    if v_kind = 'ladder' then
      update public.competition_leagues set status = 'running' where id = v_row.id;
    end if;
    return v_row.id;
  end if;

  if not public.competition_is_organiser(p_id) then
    raise exception 'Only the organiser can change this competition.' using errcode = '42501';
  end if;
  select * into v_row from public.competition_leagues where id = p_id for update;
  if v_row.status in ('finished', 'cancelled') then raise exception 'This competition has finished.'; end if;
  -- Before the draw anything can change; after it, only the words and the dates.
  update public.competition_leagues set
    name = v_name,
    about = v_about,
    province = v_province,
    club_id = v_club,
    entry_fee_cents = case when v_row.status = 'entries' then v_fee else entry_fee_cents end,
    entries_close_at = case when v_row.status = 'entries' then coalesce(v_close, entries_close_at) else entries_close_at end,
    starts_on = case when v_row.status = 'entries' then coalesce(v_starts, starts_on) else starts_on end,
    max_handicap = case when v_row.status = 'entries' then v_max else max_handicap end,
    qualifiers_per_group = case when v_row.status = 'entries' then coalesce(nullif(p ->> 'qualifiers_per_group', '')::smallint, qualifiers_per_group) else qualifiers_per_group end,
    round_days = coalesce(nullif(p ->> 'round_days', '')::smallint, round_days),
    points_win = case when v_row.status = 'entries' then coalesce(nullif(p ->> 'points_win', '')::smallint, points_win) else points_win end,
    points_half = case when v_row.status = 'entries' then coalesce(nullif(p ->> 'points_half', '')::smallint, points_half) else points_half end,
    challenge_reach = coalesce(nullif(p ->> 'challenge_reach', '')::smallint, challenge_reach),
    challenge_days = coalesce(nullif(p ->> 'challenge_days', '')::smallint, challenge_days),
    updated_at = now()
  where id = p_id;
  return p_id;
end;
$$;
revoke all on function public.competition_league_save(bigint, jsonb) from public, anon, authenticated;
grant execute on function public.competition_league_save(bigint, jsonb) to authenticated;

create or replace function public.competition_cancel(p_league_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_name text;
  r record;
begin
  if not public.competition_is_organiser(p_league_id) then
    raise exception 'Only the organiser can cancel this competition.' using errcode = '42501';
  end if;
  update public.competition_leagues set status = 'cancelled', updated_at = now()
  where id = p_league_id and status not in ('finished', 'cancelled')
  returning name into v_name;
  if v_name is null then return; end if;
  update public.competition_matches set status = 'void' where league_id = p_league_id and status <> 'confirmed';
  for r in select user_id from public.competition_entries where league_id = p_league_id and withdrawn_at is null loop
    perform public.competition_alert(r.user_id, 'competition', v_name || ' has been cancelled',
      'The organiser has cancelled it.', jsonb_build_object('href', '/compete/' || p_league_id),
      'competition-cancel-' || p_league_id);
  end loop;
end;
$$;
revoke all on function public.competition_cancel(bigint) from public, anon, authenticated;
grant execute on function public.competition_cancel(bigint) to authenticated;

-- ============ 5. Entering ============

create or replace function public.competition_enter(p_league_id bigint, p_in boolean, p_handicap numeric default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  l public.competition_leagues;
  v_hcp numeric := p_handicap;
  v_pos integer;
begin
  if v_uid is null then raise exception 'Sign in first.' using errcode = '42501'; end if;
  select * into l from public.competition_leagues where id = p_league_id for update;
  if l.id is null or not public.competition_can_view(p_league_id) then
    raise exception 'That competition is not open to you.' using errcode = '42501';
  end if;

  if not p_in then
    if l.kind = 'league' and l.status <> 'entries' then
      raise exception 'The draw is made. Ask the organiser to take you out.';
    end if;
    select ladder_position into v_pos from public.competition_entries where league_id = p_league_id and user_id = v_uid and withdrawn_at is null;
    if l.kind = 'ladder' and exists (
      select 1 from public.competition_matches
      where league_id = p_league_id and status in ('open', 'reported', 'disputed') and v_uid in (player_a, player_b)
    ) then
      raise exception 'Finish your open challenge first.';
    end if;
    update public.competition_entries set withdrawn_at = now(), ladder_position = null
    where league_id = p_league_id and user_id = v_uid and withdrawn_at is null;
    if v_pos is not null then
      update public.competition_entries set ladder_position = ladder_position - 1
      where league_id = p_league_id and ladder_position > v_pos;
    end if;
    return;
  end if;

  if l.kind = 'league' and (l.status <> 'entries' or (l.entries_close_at is not null and l.entries_close_at <= now())) then
    raise exception 'Entries have closed.';
  end if;
  if l.kind = 'ladder' and l.status not in ('entries', 'running') then
    raise exception 'This ladder has finished.';
  end if;
  if v_hcp is null then select handicap into v_hcp from public.profiles where id = v_uid; end if;
  if v_hcp is null then raise exception 'Add your handicap index to enter.'; end if;
  if v_hcp < -10 or v_hcp > 54 then raise exception 'A handicap index is between +10 and 54.'; end if;
  if l.max_handicap is not null and v_hcp > l.max_handicap then
    raise exception 'This competition is for handicaps up to %.', l.max_handicap;
  end if;

  if l.kind = 'ladder' then
    select coalesce(max(ladder_position), 0) + 1 into v_pos from public.competition_entries
    where league_id = p_league_id and withdrawn_at is null;
  end if;

  insert into public.competition_entries (league_id, user_id, handicap_index, ladder_position)
  values (p_league_id, v_uid, round(v_hcp, 1), v_pos)
  on conflict (league_id, user_id) do update set
    handicap_index = excluded.handicap_index,
    withdrawn_at = null,
    entered_at = case when competition_entries.withdrawn_at is null then competition_entries.entered_at else now() end,
    ladder_position = case when competition_entries.withdrawn_at is null then competition_entries.ladder_position else excluded.ladder_position end;
end;
$$;
revoke all on function public.competition_enter(bigint, boolean, numeric) from public, anon, authenticated;
grant execute on function public.competition_enter(bigint, boolean, numeric) to authenticated;

create or replace function public.competition_mark_paid(p_league_id bigint, p_user_id uuid, p_how text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.competition_is_organiser(p_league_id) then
    raise exception 'Only the organiser can mark entry fees.' using errcode = '42501';
  end if;
  if p_how is not null and p_how not in ('cash', 'transfer', 'waived') then
    raise exception 'Paid in cash, by transfer, or waived.';
  end if;
  update public.competition_entries set paid = p_how where league_id = p_league_id and user_id = p_user_id;
  if not found then raise exception 'They have not entered.'; end if;
end;
$$;
