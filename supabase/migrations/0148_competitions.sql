-- p_winner from the caller's side: 'me', 'them' or 'half'.
create or replace function public.competition_report(p_match_id bigint, p_winner text, p_margin text)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
  m public.competition_matches;
  l public.competition_leagues;
  v_side text;
  v_winner text;
  v_holes smallint;
  v_margin text;
  v_other uuid;
  v_name text;
  v_org uuid;
begin
  select * into m from public.competition_matches where id = p_match_id for update;
  if m.id is null or v_uid is null or v_uid not in (m.player_a, m.player_b) then
    raise exception 'Only the two players can report this match.' using errcode = '42501';
  end if;
  if m.player_a is null or m.player_b is null then raise exception 'Both players are not known yet.'; end if;
  select * into l from public.competition_leagues where id = m.league_id;
  if l.status in ('finished', 'cancelled') then raise exception 'This competition has finished.'; end if;
  if m.status in ('confirmed', 'void') then raise exception 'This result is already settled.'; end if;
  if m.status = 'disputed' then raise exception 'This result is with the organiser.'; end if;

  v_side := case when v_uid = m.player_a then 'a' else 'b' end;
  v_other := case when v_side = 'a' then m.player_b else m.player_a end;
  if p_winner = 'half' then
    if m.stage not in ('group', 'ladder') then raise exception 'A knockout match can''t be halved. Play extra holes.'; end if;
    v_winner := 'half'; v_margin := 'AS'; v_holes := 0;
  elsif p_winner in ('me', 'them') then
    v_winner := case when (p_winner = 'me') = (v_side = 'a') then 'a' else 'b' end;
    v_margin := lower(btrim(coalesce(p_margin, '')));
    v_holes := public.competition_margin_holes(v_margin, m.stage not in ('group', 'ladder'));
    if v_holes is null then raise exception 'That isn''t a matchplay result. Try 3&2, 1 up or 19th.'; end if;
  else
    raise exception 'Say who won.';
  end if;

  v_name := coalesce((select nullif(btrim(first_name), '') from public.profiles where id = v_uid), 'Your opponent');

  -- The other player had already reported: the same result confirms it,
  -- a different one goes to the organiser.
  if m.status = 'reported' and m.reported_by = v_other then
    if m.winner = v_winner and coalesce(m.margin, '') = v_margin then
      update public.competition_matches set status = 'confirmed', confirmed_at = now() where id = p_match_id;
      perform public.competition_after_result(p_match_id);
      return 'confirmed';
    end if;
    update public.competition_matches set status = 'disputed',
      dispute_note = 'The players reported different results.' where id = p_match_id;
    for v_org in select * from public.competition_organisers(m.league_id) loop
      perform public.competition_alert(v_org, 'competition', 'A result needs you: ' || l.name,
        'The two players reported different results.', jsonb_build_object('href', '/compete/match/' || p_match_id),
        'competition-dispute-' || p_match_id);
    end loop;
    return 'disputed';
  end if;

  update public.competition_matches set
    status = 'reported', winner = v_winner, margin = v_margin, holes_up = v_holes,
    reported_by = v_uid, reported_at = now(), stands_at = now() + interval '48 hours'
  where id = p_match_id;
  perform public.competition_alert(v_other, 'competition', 'Confirm your result: ' || l.name,
    v_name || ' reported ' || case when v_winner = 'half' then 'a halved match'
      when (v_winner = 'a') = (v_side = 'a') then 'a win for them, ' || v_margin
      else 'a win for you, ' || v_margin end || '. It stands in 48 hours unless you dispute it.',
    jsonb_build_object('href', '/compete/match/' || p_match_id),
    'report-' || p_match_id || '-' || v_winner || '-' || v_margin);
  return 'reported';
end;
$$;
revoke all on function public.competition_report(bigint, text, text) from public, anon, authenticated;
grant execute on function public.competition_report(bigint, text, text) to authenticated;

