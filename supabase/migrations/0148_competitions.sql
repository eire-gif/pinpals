create or replace function public.open_partner_request_set(p_open_id bigint, p_on boolean, p_note text default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_uid uuid := (select auth.uid());
begin
  if v_uid is null then raise exception 'Sign in first.' using errcode = '42501'; end if;
  if not exists (select 1 from public.open_competitions where id = p_open_id and hidden_at is null and plays_on >= current_date) then
    raise exception 'That open has gone.';
  end if;
  if p_on then
    insert into public.open_partner_requests (open_id, user_id, note)
    values (p_open_id, v_uid, nullif(left(btrim(coalesce(p_note, '')), 200), ''))
    on conflict (open_id, user_id) do update set note = excluded.note;
  else
    delete from public.open_partner_requests where open_id = p_open_id and user_id = v_uid;
  end if;
end;
$$;
