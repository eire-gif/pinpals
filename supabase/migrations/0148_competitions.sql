-- The organiser's word: settle a disputed or unplayed match, give a walkover,
-- or void it. p_winner: 'a', 'b', 'half', or null with p_void.
create or replace function public.competition_resolve(p_match_id bigint, p_winner text, p_margin text, p_void boolean default false)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  m public.competition_matches;
  v_holes smallint;
  v_margin text := lower(btrim(coalesce(p_margin, '')));
begin
  select * into m from public.competition_matches where id = p_match_id for update;
  if m.id is null or not public.competition_is_organiser(m.league_id) then
    raise exception 'Only the organiser can settle a match.' using errcode = '42501';
  end if;
  if (select status from public.competition_leagues where id = m.league_id) in ('finished', 'cancelled') then
    raise exception 'This competition has finished.';
  end if;
  if m.stage = 'group' and (select status from public.competition_leagues where id = m.league_id) <> 'running' then
    raise exception 'The groups are closed: the knockout has started.';
  end if;
  if m.status = 'confirmed' and m.stage = 'ladder' then
    raise exception 'A ladder result can''t be changed once it has moved the ladder.';
  end if;
  if m.status = 'confirmed' and m.stage <> 'group' and m.next_match_id is not null
     and exists (select 1 from public.competition_matches where id = m.next_match_id and status <> 'open') then
    raise exception 'The next round has been played. Settle it there.';
  end if;
  if p_void then
    if m.stage <> 'group' and m.stage <> 'ladder' then raise exception 'A knockout match needs a winner.'; end if;
    update public.competition_matches set status = 'void', winner = null, margin = null, holes_up = 0 where id = p_match_id;
    return;
  end if;
  if m.player_a is null or m.player_b is null then raise exception 'Both players are not known yet.'; end if;
  if p_winner = 'half' then
    if m.stage not in ('group', 'ladder') then raise exception 'A knockout match can''t be halved.'; end if;
    v_margin := 'AS'; v_holes := 0;
  elsif p_winner in ('a', 'b') then
    if v_margin = 'w/o' then v_holes := 0;
    else
      v_holes := public.competition_margin_holes(v_margin, m.stage not in ('group', 'ladder'));
      if v_holes is null then raise exception 'That isn''t a matchplay result. Try 3&2, 1 up, 19th or w/o.'; end if;
    end if;
  else
    raise exception 'Say who won.';
  end if;
  update public.competition_matches set status = 'confirmed', winner = p_winner, margin = v_margin, holes_up = v_holes,
    confirmed_at = now(), reported_by = coalesce(reported_by, (select auth.uid())), reported_at = coalesce(reported_at, now())
  where id = p_match_id;
  perform public.competition_after_result(p_match_id);
end;
$$;
revoke all on function public.competition_resolve(bigint, text, text, boolean) from public, anon, authenticated;
grant execute on function public.competition_resolve(bigint, text, text, boolean) to authenticated;

