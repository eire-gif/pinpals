-- Holes up for a margin, or null when it isn't a real matchplay result.
--   '1 up', '2 up'            decided on the 18th
--   'N&M'                     N up with M to play: N = M+1, or M+2 after dormie
--   '19th', '20th', '21st' … '27th'   extra holes (knockout only)
--   'w/o'                     walkover (organiser only)
create or replace function public.competition_margin_holes(p_margin text, p_knockout boolean)
returns smallint
language plpgsql
immutable
set search_path = public
as $$
declare
  v text := lower(btrim(coalesce(p_margin, '')));
  n integer;
  m integer;
begin
  if v in ('1 up', '2 up') then return substr(v, 1, 1)::smallint; end if;
  if v ~ '^([1-9]|10)&[1-9]$' then
    n := split_part(v, '&', 1)::integer;
    m := split_part(v, '&', 2)::integer;
    if m >= 1 and n in (m + 1, m + 2) and n + m <= 18 then return n::smallint; end if;
    return null;
  end if;
  if p_knockout and v ~ '^(19th|20th|21st|22nd|23rd|2[4-7]th)$' then return 1; end if;
  return null;
end;
$$;
revoke all on function public.competition_margin_holes(text, boolean) from public, anon, authenticated;
grant execute on function public.competition_margin_holes(text, boolean) to authenticated;

-- Applies a confirmed result: moves the winner into the next knockout match,
-- moves a ladder, and finishes the competition after its final. Internal.
create or replace function public.competition_after_result(p_match_id bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  m public.competition_matches;
  l public.competition_leagues;
  v_winner uuid;
  v_loser uuid;
  v_wpos integer;
  v_lpos integer;
begin
  select * into m from public.competition_matches where id = p_match_id;
  if m.status <> 'confirmed' or m.winner is null then return; end if;
  select * into l from public.competition_leagues where id = m.league_id;
  v_winner := case m.winner when 'a' then m.player_a when 'b' then m.player_b end;
  v_loser := case m.winner when 'a' then m.player_b when 'b' then m.player_a end;

  if m.stage = 'ladder' then
    -- player_a challenged. Only a win for the challenger moves anyone.
    -- The league row is the ladder's lock: joining, leaving and challenging
    -- take it too, so two moves never shift the same places at once.
    perform 1 from public.competition_leagues where id = m.league_id for update;
    if m.winner = 'a' then
      select ladder_position into v_wpos from public.competition_entries where league_id = m.league_id and user_id = m.player_a;
      select ladder_position into v_lpos from public.competition_entries where league_id = m.league_id and user_id = m.player_b;
      if v_wpos is not null and v_lpos is not null and v_lpos < v_wpos then
        update public.competition_entries set ladder_position = ladder_position + 1
        where league_id = m.league_id and ladder_position >= v_lpos and ladder_position < v_wpos;
        update public.competition_entries set ladder_position = v_lpos where league_id = m.league_id and user_id = m.player_a;
      end if;
    end if;
    return;
  end if;

  if m.stage <> 'group' and v_winner is not null then
    if m.next_match_id is not null then
      if m.next_slot = 'a' then
        update public.competition_matches set player_a = v_winner where id = m.next_match_id;
      else
        update public.competition_matches set player_b = v_winner where id = m.next_match_id;
      end if;
      perform public.competition_alert(v_winner, 'competition', 'Through to the next round',
        'Your next match in ' || l.name || ' is ready to arrange.',
        jsonb_build_object('href', '/compete/match/' || m.next_match_id), 'competition-next-' || m.next_match_id || '-' || v_winner);
    elsif m.stage = 'final' then
      update public.competition_leagues set status = 'finished', updated_at = now() where id = m.league_id;
    end if;
  end if;
end;
$$;
revoke all on function public.competition_after_result(bigint) from public, anon, authenticated;

