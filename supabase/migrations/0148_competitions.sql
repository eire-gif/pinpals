-- ============ 6. The draw: groups and their fixtures ============

-- p_groups: [[uuid, uuid, uuid], [uuid, uuid, uuid, uuid], …]. Worked out on
-- the organiser's phone (handicap-balanced by default, lib/matchplay.ts) and
-- checked here: every entrant exactly once, groups of 3 to 8, up to 26.
-- Fixtures are made here, round robin by the circle method, so every player
-- meets every other once and no one plays twice in a round.
create or replace function public.competition_draw(p_league_id bigint, p_groups jsonb)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  l public.competition_leagues;
  v_group jsonb;
  v_label text;
  v_gi integer := 0;
  v_players uuid[];
  v_n integer;
  v_round integer;
  v_i integer;
  v_a uuid;
  v_b uuid;
  v_seen uuid[] := '{}';
  v_entrants uuid[];
  v_slot integer;
  r record;
begin
  if not public.competition_is_organiser(p_league_id) then
    raise exception 'Only the organiser can make the draw.' using errcode = '42501';
  end if;
  select * into l from public.competition_leagues where id = p_league_id for update;
  if l.kind <> 'league' then raise exception 'Ladders have no draw.'; end if;
  if l.status <> 'entries' then raise exception 'The draw has already been made.'; end if;
  if jsonb_typeof(p_groups) <> 'array' or jsonb_array_length(p_groups) not between 1 and 26 then
    raise exception 'Between 1 and 26 groups.';
  end if;

  select coalesce(array_agg(user_id order by user_id), '{}') into v_entrants
  from public.competition_entries where league_id = p_league_id and withdrawn_at is null;
  if cardinality(v_entrants) < 3 then raise exception 'At least 3 entries are needed for a draw.'; end if;

  for v_group in select value from jsonb_array_elements(p_groups) loop
    v_gi := v_gi + 1;
    v_label := chr(64 + v_gi);
    if jsonb_typeof(v_group) <> 'array' then raise exception 'Each group is a list of players.'; end if;
    select array_agg(x::uuid order by ord) into v_players from jsonb_array_elements_text(v_group) with ordinality t(x, ord);
    v_n := coalesce(cardinality(v_players), 0);
    if v_n not between 3 and 8 then raise exception 'Groups are 3 to 8 players.'; end if;
    foreach v_a in array v_players loop
      if v_a is null then raise exception 'Every place in a group needs a player.'; end if;
      if not (v_a = any(v_entrants)) then raise exception 'Everyone in a group must have entered.'; end if;
      if v_a = any(v_seen) then raise exception 'Each player goes in one group, once.'; end if;
      v_seen := v_seen || v_a;
      update public.competition_entries set group_label = v_label where league_id = p_league_id and user_id = v_a;
    end loop;

    -- Circle method: an odd group gets a bye (null) so everyone sits out once.
    if v_n % 2 = 1 then v_players := v_players || null::uuid; end if;
    v_n := cardinality(v_players);
    v_slot := 0;
    for v_round in 1 .. v_n - 1 loop
      for v_i in 1 .. v_n / 2 loop
        v_a := v_players[v_i];
        v_b := v_players[v_n + 1 - v_i];
        if v_a is not null and v_b is not null then
          v_slot := v_slot + 1;
          insert into public.competition_matches (league_id, stage, group_label, round_no, slot, player_a, player_b, play_by)
          values (p_league_id, 'group', v_label, v_round, v_slot, v_a, v_b,
            coalesce(l.starts_on, current_date) + (v_round * l.round_days) - 1);
        end if;
      end loop;
      -- Rotate everyone but the first.
      v_players := array[v_players[1], v_players[v_n]] || v_players[2 : v_n - 1];
    end loop;
  end loop;

  if (select array_agg(x order by x) from unnest(v_seen) x) is distinct from v_entrants then
    raise exception 'Everyone who entered must be in a group.';
  end if;

  update public.competition_leagues set status = 'running', updated_at = now() where id = p_league_id;

  for r in select user_id, group_label from public.competition_entries where league_id = p_league_id and withdrawn_at is null loop
    perform public.competition_alert(r.user_id, 'competition', 'The draw is out: ' || l.name,
      'You''re in group ' || r.group_label || '. Your first match is ready to arrange.',
      jsonb_build_object('href', '/compete/' || p_league_id), 'competition-draw-' || p_league_id);
  end loop;
end;
$$;
revoke all on function public.competition_draw(bigint, jsonb) from public, anon, authenticated;
grant execute on function public.competition_draw(bigint, jsonb) to authenticated;

