-- ============ 11. Schedule ============

do $$
begin
  if not exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    raise notice 'pg_cron is not available here, so the competition schedule was NOT created. Expected on a local replay or in CI.';
    return;
  end if;
  if exists (select 1 from cron.job where jobname = 'pinpals-competition-results') then
    perform cron.unschedule('pinpals-competition-results');
  end if;
  perform cron.schedule('pinpals-competition-results', '*/15 * * * *', 'select public.competition_settle_due()');

  if exists (select 1 from cron.job where jobname = 'pinpals-competition-alerts') then
    perform cron.unschedule('pinpals-competition-alerts');
  end if;
  -- Every 3 minutes: send whatever is in the outbox. Same secrets as the
  -- society alerts (0143), so it works with no new set-up.
  perform cron.schedule(
    'pinpals-competition-alerts',
    '*/3 * * * *',
    $job$
      select net.http_post(
        url     := 'https://www.pinpals.ie/api/competitions/alerts/run',
        headers := jsonb_build_object(
          'Content-Type',  'application/json',
          'Authorization', 'Bearer ' || coalesce(
            (select decrypted_secret from vault.decrypted_secrets where name = 'society_alerts_cron_secret' limit 1),
            (select decrypted_secret from vault.decrypted_secrets where name = 'account_deletion_cron_secret' limit 1),
            'unset'
          )
        ),
        body    := '{}'::jsonb,
        timeout_milliseconds := 55000
      )
      where exists (select 1 from public.competition_alerts where sent_at is null);
    $job$
  );
end;
$$;

