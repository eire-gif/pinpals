-- Competitions (15 Oct 2026). Design: claude/competitions.md.
-- Mock-ups approved: canvas "PinPals Competitions" (5 boards).
--
-- Three things a member can play for, beyond a round with friends:
--
--   LEAGUES   season-long singles matchplay. Groups of 3–8 play round robin
--             (win 3, half 1 by default), the top one or two from each group
--             go into a knockout. Run by PinPals staff (open to everyone,
--             e.g. "Leinster winter matchplay") or by a group's owner/admins
--             (just for that society or crew).
--   LADDERS   a running ranking. Challenge anyone up to N places above you;
--             win and you take their place, everyone between moves down one.
--   OPENS     club open competitions that members share (or staff mark as
--             posted by the club), with the club's own booking link, and
--             "I need a partner" flags. PinPals never books or takes the
--             entry for an open: the club's own system does.
--
-- Matches are played in person and reported, not scored live:
--   - either player reports the result (winner and margin: 3&2, 1 up, 19th);
--   - the other confirms it, or disputes it to the organiser;
--   - a result nobody disputes STANDS 48 hours after it was reported
--     (competition_settle_due(), every 15 minutes);
--   - if both players report the same result it is confirmed at once; if they
--     report different results it is disputed.
-- Standings are worked out on the phone from the matches
-- (mobile/src/lib/matchplay.ts, pure and tested), the same way society
-- results and the order of merit are. The server keeps the facts and the
-- knockout and ladder moves, which must not depend on whose phone is open.
--
-- Entry fees are recorded and shown, and the organiser marks them paid (cash,
-- transfer or waived). No card payments yet: that is the next step, the same
-- way society entry fees were staged (claude/society-entry-fees.md).
--
-- Who counts as staff here: an ACTIVE admin or super_admin row in
-- staff_roles, read directly rather than through is_staff(). Since 0135
-- is_staff() is true only after two-step sign-in on the website, which an app
-- session never has (see mobile/src/lib/admin.ts), and running a PinPals
-- league from the phone is not an admin-console action.
--
-- Each table has at most one foreign key to profiles (the 0123 lesson):
-- competition_matches has none, on purpose — its players are read through
-- competition_entries.
--
-- Rollback:
--   select cron.unschedule('pinpals-competition-results'); select cron.unschedule('pinpals-competition-alerts');
--   drop table if exists public.competition_alerts, public.open_partner_requests, public.open_competitions,
--     public.competition_matches, public.competition_entries, public.competition_leagues cascade;
--   then drop every function this file creates (listed in function-grants.test.ts).

-- ============ 1. Tables ============

create table if not exists public.competition_leagues (
  id bigint generated by default as identity primary key,
  kind text not null default 'league' check (kind in ('league', 'ladder')),
  format text not null default 'singles' check (format in ('singles')),
  name text not null check (char_length(btrim(name)) between 3 and 80),
  about text check (about is null or char_length(about) <= 1000),
  -- null: a PinPals league, open to every member. Set: that group's members only.
  group_id bigint references public.groups (id) on delete cascade,
  province text check (province is null or province in ('leinster', 'munster', 'connacht', 'ulster')),
  club_id bigint references public.clubs (id) on delete set null,
  created_by uuid not null references public.profiles (id) on delete cascade,
  entry_fee_cents integer check (entry_fee_cents is null or entry_fee_cents between 0 and 100000),
  entries_close_at timestamptz,
  starts_on date,
  max_handicap numeric(3, 1) check (max_handicap is null or max_handicap between 0 and 54),
  -- Leagues
  qualifiers_per_group smallint not null default 2 check (qualifiers_per_group between 1 and 4),
  round_days smallint not null default 14 check (round_days between 3 and 60),
  points_win smallint not null default 3 check (points_win between 1 and 10),
  points_half smallint not null default 1 check (points_half between 0 and 10),
  -- Ladders
  challenge_reach smallint not null default 3 check (challenge_reach between 1 and 10),
  challenge_days smallint not null default 14 check (challenge_days between 3 and 60),
  status text not null default 'entries' check (status in ('entries', 'running', 'knockout', 'finished', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists competition_leagues_group_idx on public.competition_leagues (group_id) where group_id is not null;
create index if not exists competition_leagues_created_by_idx on public.competition_leagues (created_by);
create index if not exists competition_leagues_club_idx on public.competition_leagues (club_id) where club_id is not null;
create index if not exists competition_leagues_status_idx on public.competition_leagues (status);

create table if not exists public.competition_entries (
  league_id bigint not null references public.competition_leagues (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  handicap_index numeric(3, 1) not null check (handicap_index between -10 and 54),
  entered_at timestamptz not null default now(),
  withdrawn_at timestamptz,
  group_label text check (group_label is null or group_label ~ '^[A-Z]{1,2}$'),
  ladder_position integer check (ladder_position is null or ladder_position >= 1),
  paid text check (paid is null or paid in ('cash', 'transfer', 'waived')),
  primary key (league_id, user_id),
  -- One player per rung. Deferred: a move shifts a run of places in one
  -- statement, and they only line up again at the end of it.
  constraint competition_entries_one_per_rung unique (league_id, ladder_position) deferrable initially deferred
);
create index if not exists competition_entries_user_idx on public.competition_entries (user_id);

create table if not exists public.competition_matches (
  id bigint generated by default as identity primary key,
  league_id bigint not null references public.competition_leagues (id) on delete cascade,
  stage text not null check (stage in ('group', 'r32', 'r16', 'qf', 'sf', 'final', 'ladder')),
  group_label text,
  round_no smallint not null default 1,
  slot smallint not null default 0,
  player_a uuid,
  player_b uuid,
  play_by date,
  arranged_at timestamptz,
  arranged_club_id bigint references public.clubs (id) on delete set null,
  status text not null default 'open' check (status in ('open', 'reported', 'confirmed', 'disputed', 'void')),
  -- From player_a's side: 'a' or 'b' won, or halved.
  winner text check (winner is null or winner in ('a', 'b', 'half')),
  margin text check (margin is null or char_length(margin) <= 12),
  -- How many holes the winner won by, for the +/- column (3&2 → 3, 19th → 1).
  holes_up smallint not null default 0,
  reported_by uuid,
  reported_at timestamptz,
  stands_at timestamptz,
  confirmed_at timestamptz,
  dispute_note text check (dispute_note is null or char_length(dispute_note) <= 500),
  next_match_id bigint references public.competition_matches (id) on delete set null,
  next_slot text check (next_slot is null or next_slot in ('a', 'b')),
  created_at timestamptz not null default now(),
  check (player_a is null or player_b is null or player_a <> player_b)
);
create index if not exists competition_matches_league_idx on public.competition_matches (league_id, stage, round_no);
create index if not exists competition_matches_player_a_idx on public.competition_matches (player_a);
create index if not exists competition_matches_player_b_idx on public.competition_matches (player_b);
create index if not exists competition_matches_next_idx on public.competition_matches (next_match_id) where next_match_id is not null;
create index if not exists competition_matches_club_idx on public.competition_matches (arranged_club_id) where arranged_club_id is not null;
create index if not exists competition_matches_due_idx on public.competition_matches (stands_at) where status = 'reported';

create table if not exists public.open_competitions (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs (id) on delete cascade,
  plays_on date not null,
  title text not null check (char_length(btrim(title)) between 3 and 80),
  entry_fee text check (entry_fee is null or char_length(entry_fee) <= 40),
  booking_url text check (booking_url is null or (booking_url ~ '^https://' and char_length(booking_url) <= 500)),
  province text check (province is null or province in ('leinster', 'munster', 'connacht', 'ulster')),
  source text not null default 'member' check (source in ('member', 'club')),
  posted_by uuid not null references public.profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  hidden_at timestamptz
);
create index if not exists open_competitions_date_idx on public.open_competitions (plays_on) where hidden_at is null;
create index if not exists open_competitions_club_idx on public.open_competitions (club_id);
create index if not exists open_competitions_posted_by_idx on public.open_competitions (posted_by);

create table if not exists public.open_partner_requests (
  open_id bigint not null references public.open_competitions (id) on delete cascade,
  user_id uuid not null references public.profiles (id) on delete cascade,
  note text check (note is null or char_length(note) <= 200),
  created_at timestamptz not null default now(),
  primary key (open_id, user_id)
);
create index if not exists open_partner_requests_user_idx on public.open_partner_requests (user_id);

-- ============ 2. Who is who ============

create or replace function public.competition_staff()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.staff_roles
    where user_id = (select auth.uid()) and status = 'active' and role in ('admin', 'super_admin')
  );
$$;
revoke all on function public.competition_staff() from public, anon, authenticated;
grant execute on function public.competition_staff() to authenticated;

create or replace function public.competition_can_view(p_league_id bigint)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.competition_leagues l
    where l.id = p_league_id
      and (l.group_id is null or public.is_group_member(l.group_id, (select auth.uid())))
  );
$$;
revoke all on function public.competition_can_view(bigint) from public, anon, authenticated;
grant execute on function public.competition_can_view(bigint) to authenticated;

create or replace function public.competition_is_organiser(p_league_id bigint)
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (
    select 1 from public.competition_leagues l
    where l.id = p_league_id
      and (
        -- Whoever runs it NOW: a group's current owner and admins, or active
        -- staff for a PinPals league. Not "whoever created it" — that would
        -- outlive a demotion or a staff account being switched off.
        (l.group_id is not null and coalesce(public.group_role(l.group_id, (select auth.uid())), '') in ('owner', 'admin'))
        or (l.group_id is null and public.competition_staff())
      )
  );
$$;
revoke all on function public.competition_is_organiser(bigint) from public, anon, authenticated;
grant execute on function public.competition_is_organiser(bigint) to authenticated;

-- ============ 2b. The alert outbox ============

-- One row per recipient, written only by the functions below and sent by
-- the website (src/lib/competition-alerts.ts: the Inbox and a push to the
-- phone, through notifyUser), the same way society alerts are (0142). The
-- app asks for a send straight after a change; pg_cron sweeps up the rest,
-- including results that stand after 48 hours. Titles and bodies are built
-- here from first names, competition names, margins and dates — never from
-- notes or messages a member typed (a dispute note stays on the match), so
-- nothing private reaches a lock screen.
create table if not exists public.competition_alerts (
  id bigint generated always as identity primary key,
  -- The recipient. No foreign key to profiles: nothing embeds this table.
  member_id uuid not null,
  title text not null,
  body text not null,
  href text not null check (href ~ '^/compete(/|$)'),
  dedupe_key text not null,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  unique (member_id, dedupe_key)
);
create index if not exists competition_alerts_unsent_idx on public.competition_alerts (created_at) where sent_at is null;
alter table public.competition_alerts enable row level security;
revoke all on public.competition_alerts from anon, authenticated;

-- Internal: queue an alert. Repeats with the same key are dropped; no key
-- means always send.
create or replace function public.competition_alert(p_member uuid, p_type text, p_title text, p_body text, p_data jsonb, p_dedupe text)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.competition_alerts (member_id, title, body, href, dedupe_key)
  select p_member, left(p_title, 140), left(p_body, 300), coalesce(p_data ->> 'href', '/compete'),
    coalesce(p_dedupe, 'once-' || gen_random_uuid()::text)
  where p_member is not null
  on conflict (member_id, dedupe_key) do nothing;
$$;
revoke all on function public.competition_alert(uuid, text, text, text, jsonb, text) from public, anon, authenticated;

